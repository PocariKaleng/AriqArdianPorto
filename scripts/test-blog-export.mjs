import assert from 'node:assert/strict';
import { Buffer } from 'node:buffer';
import { readFile } from 'node:fs/promises';
import { publishedBundle, validateBundle, mapMarkdownUrls, checkPortableMarkdown, normalizeBase } from '../lib/blog-portable.mjs';

const id = 'a1111111-1111-4111-8111-111111111111';
const bytes = await readFile(new URL('../public/assets/explore/hackmd-profile.png', import.meta.url));
const url = `/api/blog/images/${id}`;
const post = { id: 'published-post', slug: 'rsa-notes', title: 'RSA notes', excerpt: 'A portable article.', tags: 'crypto', status: 'published', published_at: '2026-10-04T00:00:00.000Z', updated_at: '2026-10-04T00:00:00.000Z', markdown: `## Equations\n\n$$x^2$$\n\n![Inline](${url})\n\n![Reference][shot]\n\n[shot]: ${url}\n\n\`\`\`python\nprint("${url}")\n\`\`\`\n` };
let reads = 0;
const bundle = await publishedBundle([post, { ...post, id: 'draft-post', slug: 'private-draft', status: 'draft', markdown: 'PRIVATE DRAFT SENTINEL' }], async (postId, imageId) => {
  assert.equal(postId, post.id); assert.equal(imageId, id); reads++;
  return { mime: 'image/png', bytes };
});
assert.equal(bundle.posts.length, 1);
assert.equal(reads, 1, 'Repeated inline/reference images should export once');
assert.ok(!JSON.stringify(bundle).includes('PRIVATE DRAFT SENTINEL'));
assert.ok(bundle.posts[0].markdown.includes(`![Inline](./assets/${id}.png)`));
assert.ok(bundle.posts[0].markdown.includes(`[shot]: ./assets/${id}.png`));
assert.ok(bundle.posts[0].markdown.includes(`print("${url}")`), 'Code examples must remain unchanged');
assert.equal(await mapMarkdownUrls(`![${url}](${url})`, async () => './assets/replaced.png'), `![${url}](./assets/replaced.png)`, 'An image caption containing the URL must stay unchanged');
assert.deepEqual(Buffer.from(bundle.posts[0].assets[0].data, 'base64'), bytes);
await validateBundle(bundle);
const changed = structuredClone(bundle); changed.posts[0].slug = '../outside';
await assert.rejects(() => validateBundle(changed), /slug/);
const assetTraversal = structuredClone(bundle); assetTraversal.posts[0].assets[0].path = '../outside.png';
await assert.rejects(() => validateBundle(assetTraversal), /aman/);
const privatePost = structuredClone(bundle); privatePost.posts[0].status = 'draft';
await assert.rejects(() => validateBundle(privatePost), /Published/);
const invalidImage = structuredClone(bundle); invalidImage.posts[0].assets[0].data = Buffer.from('<script>alert(1)</script>').toString('base64');
await assert.rejects(() => validateBundle(invalidImage), /format/);
const missingImage = structuredClone(bundle); missingImage.posts[0].assets = [];
await assert.rejects(() => validateBundle(missingImage), /hilang/);
await assert.rejects(() => checkPortableMarkdown('![local](http://127.0.0.1:5174/file.png)', new Set()), /lokal/);
await assert.rejects(() => checkPortableMarkdown('![local](/api/blog/images/not-found)', new Set()), /lokal/);
await assert.rejects(() => checkPortableMarkdown('![missing][shot]\n\n[shot]: ./missing.png', new Set()), /gambar/);
assert.equal(normalizeBase('/my.portfolio'), '/my.portfolio/');
assert.throws(() => normalizeBase('/../outside'), /BLOG_BASE_PATH/);
await assert.rejects(() => publishedBundle([post], async () => null), /tidak tersedia/);
assert.equal(await mapMarkdownUrls('`/api/example`\n\n$$x^2$$', async () => 'changed'), '`/api/example`\n\n$$x^2$$');
console.log('PASS: published-only export, inline/reference image portability, byte preservation, code/LaTeX preservation, unsafe paths, missing/invalid images, local URL rejection.');
